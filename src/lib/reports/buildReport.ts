import { siteConfig } from "@/config/site";
import { assumptionsForEngine } from "@/lib/reports/assumptions";
import type { BuiltReport, ReportContext, ReportStyle } from "@/lib/reports/types";
import { escapeHtml } from "@/lib/reports/download";

function fieldLines(ctx: ReportContext) {
  return ctx.result.fields.map((f) => `${f.label}: ${f.value}`);
}

function inputLabel(ctx: ReportContext, key: string) {
  return ctx.fieldLabels?.[key] ?? key;
}

function inputEntries(ctx: ReportContext): [string, string][] {
  if (!ctx.inputs) return [];
  return Object.entries(ctx.inputs).filter(([, v]) => String(v ?? "").trim() !== "");
}

function resultsNarrative(ctx: ReportContext) {
  const lines = fieldLines(ctx);
  if (!lines.length) return "No numeric results were produced.";
  if (lines.length <= 6) return lines.join("; ") + ".";
  return `${lines.slice(0, 6).join("; ")}; and ${lines.length - 6} additional result fields.`;
}

function methodsForStyle(ctx: ReportContext, style: ReportStyle) {
  const formulaNote =
    ctx.formulas && ctx.formulas.length
      ? ` Formulas applied: ${ctx.formulas.map((f) => f.label).join("; ")}.`
      : "";
  const base =
    `Analysis was performed with the ${ctx.title} tool on ${siteConfig.name}. ` +
    `${ctx.description}. Calculations ran client-side in the browser.${formulaNote}`;

  if (style === "ama") {
    return (
      `${base} Statistical computations followed standard textbook formulas for this procedure. ` +
      `Users should verify that the chosen method matches the study design.`
    );
  }
  if (style === "plain") {
    return (
      `We used ${siteConfig.name}'s free ${ctx.title} calculator. ` +
      `It applies the usual formulas for this analysis and shows the intermediate steps.${formulaNote}`
    );
  }
  return (
    `${base} Results are reported with accompanying step-by-step calculations. ` +
    `Interpretations should be confirmed against the research design and measurement scale.`
  );
}

function resultsForStyle(ctx: ReportContext, style: ReportStyle) {
  if (ctx.result.apa && style === "apa") {
    return `${ctx.result.apa} Key values: ${resultsNarrative(ctx)}`;
  }
  if (style === "ama") {
    return `The ${ctx.title} analysis yielded the following estimates: ${resultsNarrative(ctx)}`;
  }
  if (style === "plain") {
    return `Here is what the calculator found: ${resultsNarrative(ctx)}`;
  }
  return ctx.result.apa
    ? `${ctx.result.apa} Summary of outputs: ${resultsNarrative(ctx)}`
    : `Results: ${resultsNarrative(ctx)}`;
}

function citationForStyle(ctx: ReportContext, style: ReportStyle) {
  if (ctx.result.apa) return ctx.result.apa;
  const core = resultsNarrative(ctx);
  if (style === "ama") return `${ctx.title}. ${core}`;
  if (style === "plain") return `${ctx.title}: ${core}`;
  return `${ctx.title}. ${core}`;
}

function latexBlock(ctx: ReportContext) {
  const formulaLines =
    ctx.formulas
      ?.map((f) => `% ${f.label}: ${f.latex}${f.note ? ` — ${f.note}` : ""}`)
      .join("\n") ?? "";
  const rows = ctx.result.fields
    .map((f) => `  ${escapeLatex(String(f.label))} & ${escapeLatex(String(f.value))} \\\\`)
    .join("\n");
  const apa = ctx.result.apa ? `\n\n% APA-style note\n% ${ctx.result.apa.replaceAll("\n", " ")}` : "";
  return `% ${ctx.title} — generated by ${siteConfig.name}
${formulaLines ? formulaLines + "\n" : ""}\\begin{tabular}{ll}
\\hline
Statistic & Value \\\\
\\hline
${rows || "  — & — \\\\"}
\\hline
\\end{tabular}${apa}
`;
}

function escapeLatex(s: string) {
  return s.replace(/([\\{}$&#^_~%])/g, "\\$1");
}

function csvCell(value: string | number) {
  return `"${String(value).replaceAll('"', '""')}"`;
}

function pageUrl(ctx: ReportContext) {
  return `${siteConfig.url}/calculators/${ctx.category}/${ctx.slug}`;
}

function toCsv(ctx: ReportContext) {
  const lines: string[] = [];
  lines.push("Section,Label,Value");
  lines.push(`Meta,Tool,${csvCell(ctx.title)}`);
  lines.push(`Meta,Category,${csvCell(ctx.categoryName ?? ctx.category)}`);
  lines.push(`Meta,Engine,${csvCell(ctx.engine)}`);
  lines.push(`Meta,URL,${csvCell(pageUrl(ctx))}`);
  lines.push(`Meta,Generated,${csvCell(new Date().toISOString())}`);
  lines.push(`Meta,Site,${csvCell(siteConfig.name)}`);

  for (const [k, v] of inputEntries(ctx)) {
    lines.push(`Input,${csvCell(inputLabel(ctx, k))},${csvCell(v)}`);
  }
  for (const f of ctx.formulas ?? []) {
    lines.push(`Formula,${csvCell(f.label)},${csvCell(f.latex)}`);
    if (f.note) lines.push(`Formula note,${csvCell(f.label)},${csvCell(f.note)}`);
  }
  ctx.result.steps.forEach((s, i) => {
    lines.push(`Work done,${csvCell(`${i + 1}. ${s.title}`)},${csvCell(s.detail)}`);
  });
  for (const f of ctx.result.fields) {
    lines.push(`Result,${csvCell(f.label)},${csvCell(f.value)}`);
  }
  if (ctx.result.apa) {
    lines.push(`Citation,APA,${csvCell(ctx.result.apa)}`);
  }
  return lines.join("\r\n");
}

/** Escape text for RTF (ASCII-safe with Unicode escapes). */
function rtfEscape(s: string) {
  return s
    .replace(/\\/g, "\\\\")
    .replace(/\{/g, "\\{")
    .replace(/\}/g, "\\}")
    .replace(/\r?\n/g, "\\par ")
    .replace(/[^\x00-\x7F]/g, (ch) => `\\u${ch.charCodeAt(0)}?`);
}

function rtfPara(text: string, opts?: { bold?: boolean; size?: number }) {
  const size = opts?.size ? `\\fs${opts.size}` : "\\fs22";
  const bold = opts?.bold ? "\\b " : "";
  const boldOff = opts?.bold ? "\\b0 " : "";
  return `{\\pard ${size}${bold}${rtfEscape(text)}${boldOff}\\par}\n`;
}

/** Build a real .rtf Word document (opens in Word / WordPad / LibreOffice). */
export function buildRtfReport(ctx: ReportContext, style: ReportStyle = "apa"): string {
  const report = buildReport(ctx, style);
  const url = pageUrl(ctx);
  const parts: string[] = [];
  parts.push("{\\rtf1\\ansi\\deff0");
  parts.push("{\\fonttbl{\\f0 Calibri;}{\\f1 Consolas;}}");
  parts.push("\\f0\\fs22\n");
  parts.push(rtfPara(siteConfig.name, { bold: true, size: 28 }));
  parts.push(rtfPara(siteConfig.tagline, { size: 18 }));
  parts.push(rtfPara(""));
  parts.push(rtfPara(`Complete calculation report (${style.toUpperCase()})`, { bold: true, size: 24 }));
  parts.push(rtfPara(`${ctx.title} Calculator`, { bold: true, size: 32 }));
  parts.push(rtfPara(`Category: ${ctx.categoryName ?? ctx.category}`));
  parts.push(rtfPara(`Generated: ${report.generatedAt}`));
  parts.push(rtfPara(`Source: ${url}`));
  parts.push(rtfPara(ctx.description));
  parts.push(rtfPara(""));

  parts.push(rtfPara("1. WHAT WAS ENTERED (INPUTS)", { bold: true, size: 26 }));
  const inputs = inputEntries(ctx);
  if (!inputs.length) parts.push(rtfPara("(No inputs recorded.)"));
  else for (const [k, v] of inputs) parts.push(rtfPara(`${inputLabel(ctx, k)}: ${truncate(v, 1500)}`));
  parts.push(rtfPara(""));

  parts.push(rtfPara("2. FORMULAS APPLIED", { bold: true, size: 26 }));
  if (!ctx.formulas?.length) parts.push(rtfPara("(See calculator page for textbook formulas.)"));
  else {
    for (const f of ctx.formulas) {
      parts.push(rtfPara(f.label, { bold: true }));
      parts.push(`{\\pard\\f1\\fs20 ${rtfEscape(f.latex)}\\par}\n`);
      if (f.note) parts.push(rtfPara(`Note: ${f.note}`));
    }
  }
  parts.push(rtfPara(""));

  parts.push(rtfPara("3. WHAT WAS DONE (WORKED STEPS)", { bold: true, size: 26 }));
  if (!ctx.result.steps.length) parts.push(rtfPara("(No intermediate steps were emitted for this run.)"));
  else ctx.result.steps.forEach((s, i) => parts.push(rtfPara(`${i + 1}. ${s.title} — ${s.detail}`)));
  parts.push(rtfPara(""));

  parts.push(rtfPara("4. END RESULTS", { bold: true, size: 26 }));
  for (const f of ctx.result.fields) parts.push(rtfPara(`${f.label}: ${f.value}`, { bold: true }));
  parts.push(rtfPara(""));

  parts.push(rtfPara("5. WRITE-UP / CITATION", { bold: true, size: 26 }));
  parts.push(rtfPara(report.writeUp));
  if (ctx.result.apa) parts.push(rtfPara(`APA: ${ctx.result.apa}`));
  parts.push(rtfPara(""));

  parts.push(rtfPara("6. ASSUMPTIONS", { bold: true, size: 26 }));
  for (const a of report.assumptions) parts.push(rtfPara(`- ${a}`));
  parts.push(rtfPara(""));
  parts.push(rtfPara(`Free branded report from ${siteConfig.name} (${siteConfig.domain})`));
  parts.push("}");
  return parts.join("");
}

function breakdownText(ctx: ReportContext, style: ReportStyle, report: Omit<BuiltReport, "breakdown" | "csv" | "latex" | "generatedAt" | "assumptions"> & { assumptions: string[]; generatedAt: string }) {
  const parts: string[] = [];
  parts.push(`${siteConfig.name} — Complete calculation report`);
  parts.push(`${ctx.title}`);
  parts.push(`Category: ${ctx.categoryName ?? ctx.category}`);
  parts.push(`Generated: ${report.generatedAt}`);
  parts.push(`Source: ${pageUrl(ctx)}`);
  parts.push("");
  parts.push("1. WHAT WAS ENTERED (INPUTS)");
  const inputs = inputEntries(ctx);
  if (!inputs.length) parts.push("(No inputs recorded.)");
  else for (const [k, v] of inputs) parts.push(`- ${inputLabel(ctx, k)}: ${truncate(v, 500)}`);
  parts.push("");
  parts.push("2. FORMULAS APPLIED");
  if (!ctx.formulas?.length) parts.push("(See calculator page for textbook formulas.)");
  else {
    for (const f of ctx.formulas) {
      parts.push(`- ${f.label}: ${f.latex}`);
      if (f.note) parts.push(`  Note: ${f.note}`);
    }
  }
  parts.push("");
  parts.push("3. WHAT WAS DONE (WORKED STEPS)");
  if (!ctx.result.steps.length) parts.push("(No intermediate steps were emitted for this run.)");
  else ctx.result.steps.forEach((s, i) => parts.push(`${i + 1}. ${s.title} — ${s.detail}`));
  parts.push("");
  parts.push("4. END RESULTS");
  for (const f of ctx.result.fields) parts.push(`- ${f.label}: ${f.value}`);
  parts.push("");
  parts.push("5. WRITE-UP");
  parts.push(report.writeUp);
  parts.push("");
  parts.push("6. ASSUMPTIONS");
  for (const a of report.assumptions) parts.push(`- ${a}`);
  parts.push("");
  parts.push(`Style: ${style.toUpperCase()} · Free report from ${siteConfig.name} (${siteConfig.domain})`);
  return parts.join("\n");
}

export function buildReport(ctx: ReportContext, style: ReportStyle = "apa"): BuiltReport {
  const assumptions = assumptionsForEngine(ctx.engine);
  const methods = methodsForStyle(ctx, style);
  const results = resultsForStyle(ctx, style);
  const writeUp = `Methods. ${methods}\n\nResults. ${results}`;
  const generatedAt = new Date().toISOString();
  const partial = {
    citation: citationForStyle(ctx, style),
    writeUp,
    methods,
    results,
    assumptions,
    generatedAt,
  };
  return {
    ...partial,
    latex: latexBlock(ctx),
    csv: toCsv(ctx),
    breakdown: breakdownText(ctx, style, partial),
  };
}

/** Branded HTML used by PDF print view and Word download. */
export function reportHtmlBody(ctx: ReportContext, style: ReportStyle) {
  const report = buildReport(ctx, style);
  const url = pageUrl(ctx);
  const cat = ctx.categoryName ?? ctx.category;

  const inputRows = inputEntries(ctx)
    .map(
      ([k, v]) =>
        `<tr><th>${escapeHtml(inputLabel(ctx, k))}</th><td class="mono">${escapeHtml(truncate(v, 2500))}</td></tr>`,
    )
    .join("");

  const formulaBlocks = (ctx.formulas ?? [])
    .map(
      (f) => `
      <div class="formula-card">
        <p class="formula-label">${escapeHtml(f.label)}</p>
        <p class="mono formula-math">${escapeHtml(f.latex)}</p>
        ${f.note ? `<p class="formula-note">${escapeHtml(f.note)}</p>` : ""}
      </div>`,
    )
    .join("");

  const steps = ctx.result.steps
    .map(
      (s, i) => `
      <li class="work-item">
        <span class="work-num">${i + 1}</span>
        <div>
          <p class="work-title">${escapeHtml(s.title)}</p>
          <p class="work-detail">${escapeHtml(s.detail)}</p>
        </div>
      </li>`,
    )
    .join("");

  const resultRows = ctx.result.fields
    .map(
      (f) =>
        `<tr><th>${escapeHtml(String(f.label))}</th><td class="mono result-value">${escapeHtml(String(f.value))}</td></tr>`,
    )
    .join("");

  const assumptions = report.assumptions.map((a) => `<li>${escapeHtml(a)}</li>`).join("");

  return `
    <header class="brand-banner">
      <div class="brand-mark">SCO</div>
      <div class="brand-text">
        <p class="brand-name">${escapeHtml(siteConfig.name)}</p>
        <p class="brand-tag">${escapeHtml(siteConfig.tagline)}</p>
      </div>
    </header>

    <div class="report-body">
    <p class="report-kicker">Complete calculation report · ${escapeHtml(style.toUpperCase())} style</p>
    <h1>${escapeHtml(ctx.title)} Calculator</h1>
    <p class="meta">
      Category: ${escapeHtml(cat)} · Generated ${escapeHtml(report.generatedAt)}
      <br />Source: <a href="${escapeHtml(url)}">${escapeHtml(url)}</a>
    </p>
    <p>${escapeHtml(ctx.description)}</p>

    <div class="toc">
      <strong>This free PDF includes:</strong>
      <ol>
        <li>What was entered (inputs)</li>
        <li>Formulas applied</li>
        <li>Work done (step-by-step)</li>
        <li>End results</li>
        <li>Citation write-up &amp; assumptions</li>
      </ol>
    </div>

    <h2><span class="sec">1</span> What was entered (inputs)</h2>
    ${
      inputRows
        ? `<table>
      <thead><tr><th>Input</th><th>Value</th></tr></thead>
      <tbody>${inputRows}</tbody>
    </table>`
        : `<p class="meta">No inputs were recorded for this run.</p>`
    }

    <h2><span class="sec">2</span> Formulas applied</h2>
    ${
      formulaBlocks ||
      `<p class="meta">Textbook formulas for this tool are listed on the calculator page at ${escapeHtml(siteConfig.name)}.</p>`
    }

    <h2><span class="sec">3</span> What was done (worked steps)</h2>
    ${
      steps
        ? `<ol class="work-list">${steps}</ol>`
        : `<p class="meta">This run did not emit intermediate steps; see the formulas above and final results below.</p>`
    }

    <h2><span class="sec">4</span> End results</h2>
    <table class="results-table">
      <thead><tr><th>Statistic</th><th>Value</th></tr></thead>
      <tbody>${resultRows || "<tr><td colspan='2'>No results</td></tr>"}</tbody>
    </table>

    <h2><span class="sec">5</span> Citation / write-up</h2>
    <p>${escapeHtml(report.writeUp)}</p>
    ${ctx.result.apa ? `<p><strong>APA-style line:</strong> ${escapeHtml(ctx.result.apa)}</p>` : ""}

    <h2><span class="sec">6</span> Assumptions checklist</h2>
    <ul>${assumptions}</ul>

    <h2>LaTeX results table</h2>
    <pre class="mono">${escapeHtml(report.latex)}</pre>

    <footer class="brand-footer">
      <p><strong>${escapeHtml(siteConfig.name)}</strong> · ${escapeHtml(siteConfig.domain)}</p>
      <p>Free branded PDF reports with inputs, formulas, worked steps, and results — generated in your browser.</p>
      <p>Not a substitute for professional statistical advice.</p>
    </footer>
    </div>
  `;
}

function truncate(s: string, max: number) {
  if (s.length <= max) return s;
  return `${s.slice(0, max)}…`;
}

export function slugifyFilename(title: string) {
  const base = title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "") || "statscalc-report";
  const stamp = new Date().toISOString().slice(0, 10);
  return `${base}-${stamp}`;
}
